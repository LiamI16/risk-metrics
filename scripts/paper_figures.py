TEMPLATES = Path(__file__).resolve().parent / "paper_tex"   # the .tex files copied to FIG
HANDOFF = TEMPLATES / "handoff"                             # README and captions for the package
PDFS = OUT / "pdf"          # figures compiled inside a copy of the paper (separate LaTeX run)
PACKAGE = OUT / "handoff_package"


def write_tikz_templates():
    """Copy the hand-editable TikZ files next to the generated data.

    They live in ``scripts/paper_tex/`` as real .tex, so they read and diff as LaTeX rather
    than as Python strings. Once uploaded, edits happen in Overleaf; re-upload only the
    data folders.
    """
    FIG.mkdir(parents=True, exist_ok=True)
    for src in sorted(TEMPLATES.iterdir()):
        if src.is_file():                      # paper_tex/handoff/ holds the package docs
            (FIG / src.name).write_text(src.read_text())


def _data_dictionary():
    """Describe every CSV column, read from the files themselves so it cannot go stale."""
    lines = ["# The data", "",
             "One row per sample. `code` (and `code_a/b/c`) says which point series a row",
             "belongs to, so one table serves every series in a figure:", "",
             "| code | meaning |", "|---|---|",
             "| `0`-`3` | the panel's condition fails; the units digit is the shade level |",
             "| `10`-`13` | the condition holds; the units digit is the shade level |",
             "| `10`/`11`, `20`/`21` | stochastic figures: first/second encounter, `1` = collision |",
             "", "## Files", ""]
    for csv in sorted(FIG.rglob("*.csv")):
        header = csv.read_text().splitlines()[0]
        rows = sum(1 for _ in csv.open()) - 1
        flat = csv.parent.name if csv.name == "samples.csv" else f"{csv.parent.name}_{csv.stem}"
        lines.append(f"- `{flat}.csv` — {rows:,} rows: `{header}`")
    return "\n".join(lines) + "\n"


def package():
    """Assemble the folder handed to the paper's authors, and zip it.

    Three ways in, same figures: drop-in PDFs, the TikZ sources with their data, or the
    bare CSVs. ``preview/`` lets them see the figures without compiling anything.
    """
    if PACKAGE.exists():
        shutil.rmtree(PACKAGE)
    (PACKAGE / "csv").mkdir(parents=True)
    for name in ("README.md", "captions.md"):
        shutil.copy(HANDOFF / name, PACKAGE / name)
    shutil.copytree(FIG, PACKAGE / "figures")
    shutil.copytree(OUT / "preview", PACKAGE / "preview") if (OUT / "preview").exists() else None
    (PACKAGE / "preview").mkdir(exist_ok=True)
    for png in sorted(OUT.glob("*.png")):
        shutil.copy(png, PACKAGE / "preview" / png.name)
    if PDFS.exists() and any(PDFS.glob("*.pdf")):
        shutil.copytree(PDFS, PACKAGE / "pdf")
    else:
        print("   note: no PDFs in artifacts/paper/pdf -- packaging without Option 1")
    for csv in sorted(FIG.rglob("*.csv")):                    # the bare tables, named by figure
        stem = csv.parent.name if csv.name == "samples.csv" else f"{csv.parent.name}_{csv.stem}"
        shutil.copy(csv, PACKAGE / "csv" / f"{stem}.csv")
    (PACKAGE / "csv" / "DATA.md").write_text(_data_dictionary())
    archive = shutil.make_archive(str(OUT / "risk_metrics_figures"), "zip",
                                  root_dir=PACKAGE.parent, base_dir=PACKAGE.name)
    return Path(archive)


def main(tokens):
    names = [n for n in FIGURES if not tokens or any(t in n for t in tokens)]
    if not names:
        sys.exit(f"no figure matches {tokens}; available: {', '.join(FIGURES)}")
    OUT.mkdir(parents=True, exist_ok=True)
    write_tikz_templates()
    for name in names:
        fig, notes = FIGURES[name]()
        path = OUT / f"{name}.png"
        fig.savefig(path, dpi=DPI, bbox_inches="tight")
        plt.close(fig)
        print(f"{path.relative_to(OUT.parent.parent)}")
        for line in notes:
            print(f"    {line}")
    print(f"TikZ: {FIG.relative_to(OUT.parent.parent)}/")
    if not tokens:                                   # a full run also repacks the handoff
        archive = package()
        print(f"package: {archive.relative_to(OUT.parent.parent)} "
              f"({archive.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main(sys.argv[1:])
