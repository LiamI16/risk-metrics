def _table(path, header, cols, ints=0):
    """Write one CSV table: float columns to 3 decimals, the last ``ints`` columns as integers."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fmt = ["%.3f"] * (len(cols) - ints) + ["%d"] * ints
    np.savetxt(path, np.column_stack(cols), delimiter=",", header=",".join(header),
               comments="", fmt=fmt)


def _clear_csvs(folder):
    """Remove a data folder's old CSVs, so a format change leaves no stale files behind."""
    if folder.exists():
        for f in folder.glob("*.csv"):
            f.unlink()


def _values(path, note, macros):
    """Write the generated numbers as \\def macros. Loaded inside the tikzpicture, so local."""
    lines = [f"% {note}",
             "% Generated by scripts/paper_figures.py and overwritten on every run -- don't edit.",
             "% Change look and layout in vo_style.tex and the figure's .tex instead."]
    for k, v in macros.items():
        text = f"{v:.4f}" if isinstance(v, (float, np.floating)) else str(v)
        lines.append(f"\\def\\{k}{{{text}}}")
    path.write_text("\n".join(lines) + "\n")


def _shade_levels(mag, holds):
    """Shade level per point, 0 (small) .. SHADE_LEVELS-1 (large), per class.

    Uses the matplotlib figure's own per-class percentile limits (``class_limits``), so the
    TikZ shading and the review render cannot drift apart.
    """
    lv = np.zeros(len(mag), int)
    for sel, (lo, hi) in zip((~holds, holds), class_limits(mag, holds)):
        t = np.clip((mag[sel] - lo) / max(hi - lo, 1e-12), 0.0, 1.0)
        lv[sel] = np.minimum((t * SHADE_LEVELS).astype(int), SHADE_LEVELS - 1)
    return lv


