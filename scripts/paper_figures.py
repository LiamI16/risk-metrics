OUT = Path(__file__).resolve().parent.parent / "artifacts" / "paper"
FIG = OUT / "figures"
SEED = 0
DPI = 200

# ---- Equivalence figure --------------------------------------------------------------
RADIUS = 10.0                    # per ship, so R = 20
RELPOS = np.array([48.0, 36.0])  # target relative to own
V_TARGET = np.array([-4.0, 2.0])
D_FRAC = 0.6                     # miss distance as a fraction of R: a grazing conflict
SPEED = 10.0                     # closing speed ||v_rel|| of the twin pair
EQUIV_N = 8_000                  # candidate velocities, shared by all three panels
EQUIV_PAD = 0.25                 # frame padding; also the sampling window
MARK_SIZE = 3.0                  # matplotlib scatter mark area (review PNG only)
SHADE_LEVELS = 4                 # discrete magnitude shades per class in the TikZ figure

# ---- Stochastic comparison -----------------------------------------------------------
# The same noise for every encounter
SIGMA_POS = 5.0                  # m,   = 0.25 R
SIGMA_VEL = 0.5                  # m/s
STOCH_N = 5_000                  # samples per encounter. Captions quote P[collision] to two
                                 # decimals: at 5k its Monte-Carlo sd is ~0.005
HIST_BINS = 80

COLLINEAR_CLOSING = Scenario("collinear_closing", (0, 0), (0, 5.0), (0, 120), (0, 4.5))
PAIR = (CROSSING, COLLINEAR_CLOSING)


def noise_models():
    """Per-channel (position, velocity) noise for each stochastic figure.

    The uniform ellipse is sized to a Gaussian level set: ``uniform_like`` gives semi-axes
    of 2 sigma, so its hard edge is exactly the Gaussian 2-sigma ellipse -- and a uniform
    ellipse of semi-axis 2 sigma also has per-axis variance sigma^2, so the two models
    carry the same covariance. Only the *shape* of the distribution differs. Here that is
    a disc of radius 10 m in position and 1 m/s in velocity.
    """
    Sp, Sv = SIGMA_POS ** 2 * np.eye(2), SIGMA_VEL ** 2 * np.eye(2)
    return {
        "gaussian": (Sp, Sv),
        "uniform_ellipse": (uniform_like(Sp, "ellipse"), uniform_like(Sv, "ellipse")),
    }


def twin_pair(relpos, v_target, R, d_frac=D_FRAC, speed=SPEED):
    """Two own velocities with equal DCPA and opposite-sign TCPA.

    Tilting the straight-at relative direction by ``asin(d / ||p_rel||)`` sets the miss
    distance to ``d``; negating the relative velocity reverses time, which preserves DCPA
    (it depends on the *line*) and flips the sign of TCPA.
    """
    p = np.asarray(relpos, dtype=float)
    dist = float(np.linalg.norm(p))
    phi = np.arcsin(d_frac * R / dist)
    ct, st = np.cos(phi), np.sin(phi)
    u = (-p / dist) @ np.array([[ct, st], [-st, ct]])
    w = speed * u
    return np.asarray(v_target) - w, np.asarray(v_target) + w


