def fig_equivalence():
    own = Ship((0.0, 0.0), (0.0, 0.0), Circle(RADIUS))
    target = Ship(RELPOS, V_TARGET, Circle(RADIUS))
    R = 2.0 * RADIUS
    vc, vs = twin_pair(RELPOS, V_TARGET, R)

    fig = equivalence_figure(own, target, vc, vs, pad_frac=EQUIV_PAD, n_samples=EQUIV_N,
                             seed=SEED, mark_size=MARK_SIZE)

    # The identical draw: same frame, seed and n as the figure.
    c, half = _frame([(0.0, 0.0), V_TARGET, vc, vs], EQUIV_PAD)
    pts = _frame_samples(c, half, EQUIV_N, np.random.default_rng(SEED))
    truth = _vo_membership(pts, RELPOS, V_TARGET, R)          # Thm. 1's LHS, solved directly
    tcpa, dcpa = _cpa_fields(pts, RELPOS, V_TARGET)
    tau_pair, d_pair = _cpa_fields(np.stack([vc, vs]), RELPOS, V_TARGET)
    tests = {"a": (dcpa <= R, dcpa), "b": (tcpa > 0, np.abs(tcpa)),
             "c": ((dcpa <= R) & (tcpa > 0), None)}
    wrong = {k: int((h & ~truth).sum()) for k, (h, _) in tests.items()}

    # ---- TikZ data: one table, every sample once ------------------------------------
    # All three panels plot the same points, each colored by its own criterion, so the
    # table carries one class code per panel: tens digit 1 = the condition holds, 0 = it
    # fails; units digit = magnitude shade level (0 = smallest). In the .tex, each \addplot
    # keeps the rows with its code.
    out = FIG / "equivalence"
    _clear_csvs(out)
    codes = {key: 10 * holds.astype(int) + (0 if mag is None else _shade_levels(mag, holds))
             for key, (holds, mag) in tests.items()}
    _table(out / "samples.csv", ["x", "y", "dcpa", "tcpa", "code_a", "code_b", "code_c"],
           [pts[:, 0], pts[:, 1], dcpa, tcpa, codes["a"], codes["b"], codes["c"]], ints=3)

    # ---- TikZ geometry: every line is closed form, handed over as endpoints --------
    # Endpoints in axis units rather than TikZ polar coordinates: inside a pgfplots axis a
    # polar radius is in canvas units, which draws a correctly angled line in the wrong place.
    theta = np.arcsin(R / np.linalg.norm(RELPOS))
    los = np.arctan2(RELPOS[1], RELPOS[0])
    edges = [np.array([np.cos(los + s * theta), np.sin(los + s * theta)]) for s in (1, -1)]
    along = np.array([-RELPOS[1], RELPOS[0]]) / np.linalg.norm(RELPOS)   # TCPA = 0 line
    L = 4.0 * half                                                        # past the frame
    vO = V_TARGET
    macros = {"xmin": c[0] - half, "xmax": c[0] + half, "ymin": c[1] - half, "ymax": c[1] + half,
         "apexX": vO[0], "apexY": vO[1],
              # the closed forms the endpoints come from; see figures/README.md
              "pRelX": RELPOS[0], "pRelY": RELPOS[1],
              "pRelNorm": float(np.linalg.norm(RELPOS)), "safetyR": R,
              "coneHalfAngleDeg": float(np.degrees(theta)),
              "losBearingDeg": float(np.degrees(los)),
              "edgeOneBearingDeg": float(np.degrees(los + theta)),
              "edgeTwoBearingDeg": float(np.degrees(los - theta)),
              "tcpaLineA": RELPOS[0], "tcpaLineB": RELPOS[1],
              "tcpaLineC": float(RELPOS @ vO)}
    for name, e in zip(("One", "Two"), edges):
        a, b = vO - L * e, vO + L * e
        macros |= {f"bow{name}Ax": a[0], f"bow{name}Ay": a[1], f"bow{name}Bx": b[0], f"bow{name}By": b[1],
              f"cone{name}X": b[0], f"cone{name}Y": b[1]}
    a, b = vO - L * along, vO + L * along
    macros |= {"tcpaAx": a[0], "tcpaAy": a[1], "tcpaBx": b[0], "tcpaBy": b[1],
          "apprX": vc[0], "apprY": vc[1], "recX": vs[0], "recY": vs[1],
          "apprDcpa": f"{d_pair[0]:.1f}", "recDcpa": f"{d_pair[1]:.1f}",
          "apprTcpa": f"{tau_pair[0]:+.1f}", "recTcpa": f"{tau_pair[1]:+.1f}"}
    _values(out / "values.tex", "Equivalence figure: frame, closed-form lines, twin pair.", macros)

    caption = (f"Marks are {EQUIV_N:,} candidate velocities drawn uniformly over the plotted "
               f"range. Used as a test of VO membership, DCPA <= R alone is wrong on "
               f"{wrong['a']:,} of them and TCPA > 0 alone on {wrong['b']:,}; together they "
               f"are wrong on {wrong['c']}.")
    (out / "caption_numbers.txt").write_text(caption + "\n")

    return fig, [
        f"twin pair: DCPA {d_pair[0]:.1f} / {d_pair[1]:.1f} m, "
        f"TCPA {tau_pair[0]:+.1f} / {tau_pair[1]:+.1f} s",
        f"used as a VO test, wrong on: DCPA<=R {wrong['a']}/{EQUIV_N}, "
        f"TCPA>0 {wrong['b']}/{EQUIV_N}, both {wrong['c']}/{EQUIV_N}",
    ]


def _square_frame(points, pad_frac=0.18):
    """Square (center, half-width) framing ``points`` -- the matplotlib panel's rule."""
    P = np.asarray(points, dtype=float)
    lo, hi = P.min(axis=0), P.max(axis=0)
    return 0.5 * (lo + hi), max(0.5 * float((hi - lo).max()) * (1 + pad_frac), 1e-6)


def fig_stochastic(model):
    pos, vel = noise_models()[model]
    fig = stochastic_comparison_figure(PAIR, pos, vel, n=STOCH_N, seed=SEED)

    out = FIG / f"stochastic_{model}"
    _clear_csvs(out)
    macros, notes, caption, samples, hists = {}, [], [], [], []
    for row, (sc, tag) in enumerate(zip(PAIR, ("rowA", "rowB"))):   # the figure's seeds
        own, target = sc.ships()
        m = sc.metrics()
        R = m.safety_radius
        s = sample_cpa(own, target, pos, vel, n=STOCH_N, rng=np.random.default_rng(SEED + row))
        tau, d = s.tcpa, s.dcpa
        hit = (np.abs(d) <= R) & (tau >= 0)
        p_hit = float(hit.mean())

        # joint panel: the matplotlib limits (robust percentiles, DCPA symmetric about 0)
        xlo, xhi = np.percentile(tau, [0.5, 99.5])
        xpad = 0.05 * (xhi - xlo + 1e-9)
        xlo, xhi = xlo - xpad, xhi + xpad
        ymax = 1.05 * float(np.percentile(np.abs(d), 99.5))
        # Histograms are binned here rather than by pgfplots: its hist filter ignores row
        # selection, and it cannot draw the sideways marginal. group = 10*row + (0 TCPA, 1 DCPA)
        for var, data, lo, hi in ((0, tau, xlo, xhi), (1, d, -ymax, ymax)):
            dens, edges = np.histogram(data, bins=HIST_BINS, range=(lo, hi), density=True)
            hists.append(np.column_stack([np.full(edges.size, 10 * (row + 1) + var),
                                          edges, np.append(dens, dens[-1])]))

        # velocity panel: each sample's equivalent own velocity
        vown = np.asarray(target.vel) - s.relvel
        p1, p99 = np.nanpercentile(vown, [1, 99], axis=0)
        vel_center, vel_half = _square_frame([target.vel, own.vel, p1, p99])
        # every sample once: code = 10*row + collision (0 no, 1 yes). Panels keep their own
        # rows and discard samples outside their axis range, so TCPA tails never reach TeX.
        samples.append(np.column_stack([tau, d, vown[:, 0], vown[:, 1],
                                        10 * (row + 1) + hit.astype(int)]))
        apex = np.asarray(target.vel, float)
        e1, e2 = VelocityObstacle.from_ships(own, target).cone.edges

        det = (m.TCPA() > 0) and (abs(m.DCPA()) <= R)
        macros |= {f"{tag}name": sc.name.replace("_", " "), f"{tag}R": R,
              f"{tag}jxmin": xlo, f"{tag}jxmax": xhi, f"{tag}jymin": -ymax, f"{tag}jymax": ymax,
              f"{tag}tcpa": m.TCPA(), f"{tag}dcpa": m.DCPA(),
              f"{tag}ntcpa": f"{m.TCPA():.0f}", f"{tag}ndcpa": f"{abs(m.DCPA()):.0f}",
              f"{tag}verdict": "in VO" if det else "outside VO", f"{tag}P": f"{p_hit:.2f}",
              f"{tag}vxmin": vel_center[0] - vel_half, f"{tag}vxmax": vel_center[0] + vel_half,
              f"{tag}vymin": vel_center[1] - vel_half, f"{tag}vymax": vel_center[1] + vel_half,
              f"{tag}apexX": apex[0], f"{tag}apexY": apex[1],
              f"{tag}pRelNorm": float(np.linalg.norm(m.relpos)),
              f"{tag}coneHalfAngleDeg": float(np.degrees(np.arcsin(R / np.linalg.norm(m.relpos)))),
              f"{tag}losBearingDeg": float(np.degrees(np.arctan2(m.relpos[1], m.relpos[0]))),
              f"{tag}ownX": own.vel[0], f"{tag}ownY": own.vel[1],
              f"{tag}coneOneX": apex[0] + 4 * vel_half * e1[0], f"{tag}coneOneY": apex[1] + 4 * vel_half * e1[1],
              f"{tag}coneTwoX": apex[0] + 4 * vel_half * e2[0], f"{tag}coneTwoY": apex[1] + 4 * vel_half * e2[1]}

        t1, t99 = np.percentile(tau, [1, 99])
        notes.append(f"{sc.name:18s} P[collision] {p_hit:.2f}   "
                     f"TCPA 1-99%: [{t1:.0f}, {t99:.0f}] s")
        caption.append(f"{sc.name.replace('_', ' ')}: P[collision] = {p_hit:.2f}")

    sample_table, hist_table = np.vstack(samples), np.vstack(hists)
    _table(out / "samples.csv", ["tcpa", "dcpa", "vE", "vN", "code"],
           [sample_table[:, c] for c in range(5)], ints=1)
    _table(out / "histograms.csv", ["edge", "density", "group"],
           [hist_table[:, 1], hist_table[:, 2], hist_table[:, 0]], ints=1)
    _values(out / "values.tex", f"Stochastic comparison, {model.replace('_', ' ')} noise.", macros)
    (out / "caption_numbers.txt").write_text(
        f"{STOCH_N:,} samples per encounter. " + "; ".join(caption) + ".\n")
    return fig, notes


FIGURES = {
    "equivalence_sampled": fig_equivalence,
    "stochastic_comparison_gaussian": partial(fig_stochastic, "gaussian"),
    "stochastic_comparison_uniform_ellipse": partial(fig_stochastic, "uniform_ellipse"),
}


